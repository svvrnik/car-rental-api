CREATE TABLE users(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY ,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL ,
    first_name VARCHAR(255) NOT NULL ,
    last_name VARCHAR(255) NOT NULL ,
    role VARCHAR(255) NOT NULL CHECK ( role IN ('USER','ADMIN')) ,
    account_balance NUMERIC(10,2) NOT NULL
);

CREATE TABLE cars(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    brand VARCHAR(255) NOT NULL,
    model VARCHAR(255) NOT NULL ,
    description VARCHAR(1000) NOT NULL ,
    license_plate VARCHAR(255) NOT NULL UNIQUE ,
    owner_id BIGINT REFERENCES users(id),
    status VARCHAR(255) NOT NULL CHECK ( status IN ('PENDING', 'AVAILABLE', 'UNAVAILABLE', 'REJECTED', 'RENTED')),
    price_per_day NUMERIC(10,2) NOT NULL
);

CREATE TABLE car_image(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    image_url VARCHAR(255) NOT NULL,
    is_main BOOLEAN NOT NULL ,
    car_id BIGINT REFERENCES cars(id) NOT NULL
);

CREATE TABLE rentals(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    car_id BIGINT NOT NULL REFERENCES cars(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    start_date TIMESTAMP NOT NULL ,
    end_date TIMESTAMP NOT NULL ,
    total_cost NUMERIC(10,2) NOT NULL ,
    status VARCHAR(255) NOT NULL CHECK ( status IN ('ACTIVE', 'COMPLETED', 'CANCELLED') )
);

CREATE TABLE transactions(
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY ,
    sender_id BIGINT REFERENCES users(id),
    receiver_id BIGINT REFERENCES users(id),
    amount NUMERIC(10,2) NOT NULL,
    type VARCHAR(255) NOT NULL CHECK ( type IN ('RENTAL_PAYMENT','PAYOUT','DEPOSIT')),
    created_at TIMESTAMP NOT NULL
);